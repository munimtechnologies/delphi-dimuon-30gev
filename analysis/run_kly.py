#!/usr/bin/env python3
"""run_kly: do the LEP1 Higgs searches (and ALEPH's own kinematics) exclude the two published
models of Ko, Li and Yu (arXiv:1610.07526) for the ALEPH 30 GeV dimuon excess?

Model B (Z' coupling b to a heavy vector-like B, built to escape the LHC Drell-Yan bound) and
model Q (Z -> Z' phi), generated by kly.py, hadronised with Pythia 8, passed through the four LEP1
H Z*(-> mu mu) selections of lephz.py (one definition), and confronted with their candidates.
Also reports the angle between each muon and the nearest Durham jet of the rest of the event
(ALEPH reports a muon within 15 deg of a leading jet in all its excess events).

Needs kly.py, lephz.py, efhz.py, eff4f.py, lep4f.py and xkin's xme.py, evana.py, fadgen.py,
run_xkin.py next to it (the job fetches the published ones from the public repo), numpy, pythia8mc.

MV2 of Munim, Inc. (mv2@munimtech.com). Made with AI agents. Apache-2.0.
"""
import argparse
import json
import multiprocessing as mp
import os
import sys
import time

import numpy as np

import kly
import lephz

QUANT = (0.05, 0.25, 0.5, 0.75, 0.95)


def run_model(task):
    label, n, seed, tmpdir, outdir, budget = task
    import xme
    import run_xkin
    t0 = time.time()
    kind, par, layout, sig_id = kly.MODELS[label]
    rng = np.random.default_rng(seed)
    ev = kly.generate(label, n, rng)
    t_gen = time.time() - t0
    ez = (ev['q1'] + ev['q2'])[:, 0]
    eb = np.sort(np.stack([ev['p1'][:, 0], ev['p2'][:, 0]], 1), 1)
    parton_q = {"E_Zprime": [round(float(x), 2) for x in np.quantile(ez, QUANT)],
                "E_b_soft": [round(float(x), 2) for x in np.quantile(eb[:, 0], QUANT)],
                "E_b_hard": [round(float(x), 2) for x in np.quantile(eb[:, 1], QUANT)]}
    lhe = os.path.join(tmpdir, 'kly_%s.lhe' % label)
    xme.write_lhe(lhe, layout, ev)
    mphi = par.get("m_phi", 30.4)
    sets = run_xkin.pythia_common(seed % 900000000 + 1) + [
        "Beams:frameType = 4", "Beams:LHEF = %s" % lhe,
        "32:m0 = 30.4", "32:mWidth = 1.78", "32:mMin = 5.", "32:mMax = 85.",
        "35:m0 = 30.4", "35:mWidth = 1.78", "35:mMin = 5.", "35:mMax = 85.",
        "36:m0 = %.3f" % mphi, "36:mWidth = 0.01", "36:mMin = 5.", "36:mMax = 85."]
    py = run_xkin.make_pythia(sets)
    counts = lephz.new_counts()
    rec, ang_min, ang_max = [], [], []
    nok = nfail = nopair = 0
    stopped = False
    for k in range(n):
        if time.time() - t0 > budget:
            stopped = True
            break
        if not py.next():
            nfail += 1
            if nfail > 50 and nok == 0:
                break
            continue
        nok += 1
        ids, p4, ch, sig, vtx = run_xkin.extract(py.event, (sig_id,))
        smu = np.nonzero(sig & (np.abs(ids) == 13))[0]
        if len(smu) != 2 or ch[smu[0]] * ch[smu[1]] >= 0:
            nopair += 1
            continue
        i, j = int(smu[0]), int(smu[1])
        r = lephz.evaluate(ids, p4, ch, i, j)
        lephz.accumulate(counts, r)
        if r["acc"] and r["in_window"]:
            rec.append(r["recoil"])
            ctx = lephz.make_ctx(ids, p4, ch)
            jets = lephz.rest_jets(ctx, i, j, 0.02)
            a = sorted(lephz.nearest_jet_angle(ctx["p4"], q, jets, 1.0) for q in (i, j))
            ang_min.append(a[0])
            ang_max.append(a[1])
        if nok % 250 == 0:
            with open(os.path.join(outdir, 'partial_%s.json' % label), 'w') as f:
                json.dump(dict(model=label, n_hadronised=nok, counts=counts,
                               seconds=round(time.time() - t0, 1)), f)
    q = {}
    for key, v in (("recoil", rec), ("mu_jet_angle_min", ang_min), ("mu_jet_angle_max", ang_max)):
        a = np.array(v, float)
        a = a[np.isfinite(a)]
        q[key] = [round(float(x), 3) for x in np.quantile(a, QUANT)] if len(a) else []
    frac = {}
    if rec:
        r_ = np.array(rec)
        am = np.array(ang_min)
        frac = {"recoil_gt_40": round(float(np.mean(r_ > 40.0)), 4),
                "recoil_lt_15": round(float(np.mean(r_ < 15.0)), 4),
                "mu_jet_min_lt_15deg": round(float(np.mean(am < 15.0)), 4)}
    stats = dict(model=label, kind=kind, params=par, parton=ev['stats'], parton_quantiles=parton_q,
                 n_hadronised=nok, n_fail=nfail, n_no_truth_pair=nopair, stopped_by_budget=stopped,
                 seconds_generation=round(t_gen, 1), seconds=round(time.time() - t0, 1),
                 fractions_acc_window=frac)
    return label, counts, q, stats


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='/out')
    ap.add_argument('--nsig', type=int, default=8000)
    ap.add_argument('--workers', type=int, default=2)
    ap.add_argument('--seed', type=int, default=20261121)
    ap.add_argument('--models', default='B110,B180,B110L,Q12,Q30,Q50')
    ap.add_argument('--budget-min', type=float, default=30.0, help='wall-clock budget per model')
    a = ap.parse_args()
    import eff4f
    import efhz
    import lep4f
    import xme
    print('VERSIONS', kly.VERSION, lephz.VERSION, efhz.VERSION, eff4f.VERSION, lep4f.VERSION, flush=True)
    os.makedirs(a.out, exist_ok=True)
    tmp = '/tmp/kly'
    os.makedirs(tmp, exist_ok=True)
    models = a.models.split(',')
    tasks = [(m, a.nsig, a.seed + 7 * k + 1, tmp, a.out, a.budget_min * 60.0)
             for k, m in enumerate(models)]
    with mp.Pool(min(a.workers, len(tasks))) as pool:
        results = pool.map(run_model, tasks, chunksize=1)
    out = dict(tool=kly.VERSION, lephz=lephz.VERSION, efhz=efhz.VERSION, eff4f=eff4f.VERSION,
               lep4f=lep4f.VERSION, made_by='MV2 of Munim, Inc. (made with AI agents)',
               reference='Ko, Li, Yu, arXiv:1610.07526 (models II and III)',
               f_gen=efhz.f_gen(), id_eff_per_muon=eff4f.ID_EFF,
               n_obs={s: {"compatible": lephz.n_obs(s), "all": lephz.n_obs(s, "all")} for s in lephz.ALL_SET},
               pred_if_eps_1={s: lephz.predict(s, 1.0) for s in lephz.ALL_SET},
               models={})
    for label, c, q, st in results:
        print('TASK', json.dumps(st, default=str), flush=True)
        eps = {k: lephz.eps(c, k) for k in lephz.KEYS}
        nom = {s: eps["%s:nominal" % s][0] for s in lephz.ALL_SET}
        out["models"][label] = dict(stats=st, counts=c, quantiles_acc_window=q,
                                    eps={k: [round(v[0], 4), round(v[1], 4)] for k, v in eps.items()},
                                    confront_nominal=lephz.confront_all(nom))
    with open(os.path.join(a.out, 'kly-summary.json'), 'w') as f:
        json.dump(out, f, indent=1, default=str)

    print('\nLEP1 H Z*(mu mu) selections on Ko-Li-Yu model events; eps vs ALEPH acceptance, 20-40 GeV, no muon ID')
    for label, r in out["models"].items():
        print('%s n_acc=%d  ' % (label, r["counts"]["n_acc"]) +
              '  '.join('%s=%.3f' % (k, r["eps"][k][0]) for k in lephz.KEYS))
    print('\ncut-by-cut (fraction of acceptance-and-window events passing each nominal cut):')
    for label, r in out["models"].items():
        n = max(r["counts"]["n_acc"], 1)
        print(label, ' '.join('%s=%.3f' % (k[4:], v / n) for k, v in r["counts"]["cut"].items()))
    print('\npredicted events for eps = 1 (ALEPH central rate):',
          json.dumps({s: round(v, 1) for s, v in out["pred_if_eps_1"].items()}))
    print('signal-compatible candidates:', json.dumps(out["n_obs"]))
    print('\nconfrontation (nominal selections; b = 0):')
    for label, r in out["models"].items():
        for k in ("nominal3|compatible|central", "nominal3|all|lit1.1e-5", "L3+DELPHI|all|central",
                  "L3+DELPHI|all|lit1.1e-5", "L3_96|compatible|central", "L3_96|compatible|lit1.1e-5",
                  "DELPHI94|compatible|lit1.1e-5", "ALEPH96|compatible|central", "OPAL97|compatible|central"):
            c = r["confront_nominal"][k]
            print('%s %-34s n=%d pred=%7.2f s_up=%5.2f mu_max=%.4f p=%.3g z=%.2f' % (
                label, k, c["n_obs"], c["pred"], c["s_up_95"], c["mu_max"], c["p"], c["z"]))
    print('\nquantiles (5,25,50,75,95 %) in acceptance and window; parton-level energies:')
    for label, r in out["models"].items():
        print(label, json.dumps(r["quantiles_acc_window"]), json.dumps(r["stats"]["fractions_acc_window"]),
              json.dumps(r["stats"]["parton_quantiles"]))
    print('\nparton stats:')
    for label, r in out["models"].items():
        print(label, json.dumps(r["stats"]["parton"], default=str))
    last = []
    for label, r in out["models"].items():
        e = r["eps"]
        c = r["confront_nominal"]
        last.append('%s eps A/L3/D/O %.3f/%.3f/%.3f/%.3f L3+D lit p=%.2g L3 lit p=%.2g over=%s' % (
            label, e["ALEPH96:nominal"][0], e["L3_96:nominal"][0], e["DELPHI94:nominal"][0],
            e["OPAL97:nominal"][0], c["L3+DELPHI|all|lit1.1e-5"]["p"], c["L3_96|compatible|lit1.1e-5"]["p"],
            r["stats"]["parton"].get("n_over")))
    print('\nKLY: ' + ' | '.join(last))
    sys.stdout.flush()
    return 0


if __name__ == '__main__':
    sys.exit(main())
